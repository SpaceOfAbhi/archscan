**Supporting signals:**
- No single shared `data/` or `domain/` folder at `lib/` root level (features own their layers)
- Shared code isolated in `core/`, `shared/`, or `common/`
- Dependencies: any state management package is acceptable

**Distinguish from Clean Architecture:**
- Clean Architecture → layers are at the root, features are inside layers
- Feature-First → features are at the root, layers are inside features

